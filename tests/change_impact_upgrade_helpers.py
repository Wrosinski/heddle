"""Rebuild hosts recorded before change-impact re-binding, and project status.

The fixture under ``tests/fixtures/workspaces/change-impact-upgrade/`` holds a
synthetic host recorded by the build that preceded change-impact re-binding.
``history.json`` holds the host's Git commits as complete trees, and each
snapshot file holds the exact working tree at one point of the recorded
journey with the status that build reported for it. Trees name contents by
SHA-256 in ``blobs.json``, which stores each content once as a line list, so
the stored text never carries trailing whitespace or collectable test modules;
joining the lines restores the exact bytes, which are checked against their
recorded SHA-256 on every restore. The fixture was recorded by the build at
base commit 50e72d3 and must never be regenerated by a later build.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any

FIXTURE = Path(__file__).resolve().parent / "fixtures/workspaces/change-impact-upgrade"
FEATURE = "operational-example"
SPEC = f"docs/features/runtime/{FEATURE}.md"
SNAPSHOTS = (
    "scaffold-unopened",
    "scaffold-attempt-only",
    "scaffold-partial",
    "robustness-open",
)
_IDENTITY = {
    "GIT_AUTHOR_NAME": "Fixture",
    "GIT_AUTHOR_EMAIL": "fixture@example.invalid",
    "GIT_COMMITTER_NAME": "Fixture",
    "GIT_COMMITTER_EMAIL": "fixture@example.invalid",
}


@dataclass(frozen=True)
class RecordedHost:
    """A rebuilt host and what the pre-change build reported for it."""

    root: Path
    state: Path
    record: dict[str, Any]

    @property
    def workspace(self) -> Path:
        return self.state.parent


def load_snapshot(name: str) -> dict[str, Any]:
    return json.loads((FIXTURE / f"{name}.json").read_text(encoding="utf-8"))


def _git(root: Path, *args: str, env: dict[str, str] | None = None) -> str:
    return subprocess.run(
        ["git", "-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null", *args],
        cwd=root,
        check=True,
        capture_output=True,
        text=True,
        env={**os.environ, **(env or {})},
    ).stdout


def _blobs() -> dict[str, list[str]]:
    return json.loads((FIXTURE / "blobs.json").read_text(encoding="utf-8"))["blobs"]


def _write_tree(
    root: Path, files: dict[str, dict[str, Any]], blobs: dict[str, list[str]]
) -> None:
    for child in root.iterdir():
        if child.name == ".git":
            continue
        if child.is_dir() and not child.is_symlink():
            shutil.rmtree(child)
        else:
            child.unlink()
    for relative, entry in files.items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        content = "\n".join(blobs[entry["sha256"]]).encode("utf-8")
        assert hashlib.sha256(content).hexdigest() == entry["sha256"], (
            f"FAIL AC-15: upgrade fixture blob for {relative} no longer matches "
            "its recorded sha256; the fixture must never be edited or regenerated"
        )
        target.write_bytes(content)
        target.chmod(entry["mode"])


def rebuild(name: str, parent: Path) -> RecordedHost:
    """Replay the recorded commits, then lay down one snapshot's working tree.

    Commits are replayed with their recorded identity and dates, so every
    object id (the feature baseline included) equals the recorded one.
    """
    history = json.loads((FIXTURE / "history.json").read_text(encoding="utf-8"))
    snapshot = load_snapshot(name)
    blobs = _blobs()
    root = parent / "host"
    root.mkdir(parents=True)
    _git(root, "init", "-q", "-b", history["branch"])
    for commit in history["commits"]:
        _write_tree(root, commit["files"], blobs)
        _git(root, "add", "-A")
        dated = {
            **_IDENTITY,
            "GIT_AUTHOR_DATE": commit["date"],
            "GIT_COMMITTER_DATE": commit["date"],
        }
        _git(root, "commit", "-q", "-m", commit["message"], env=dated)
        oid = _git(root, "rev-parse", "HEAD").strip()
        assert oid == commit["oid"], (
            f"ERROR fixture replay: commit {commit['message']!r} is {oid}, "
            f"recorded {commit['oid']}"
        )
    assert snapshot["head"] == history["commits"][-1]["oid"]
    _write_tree(root, snapshot["files"], blobs)
    pointer = root / ".git/heddle/active-feature"
    pointer.parent.mkdir(parents=True, exist_ok=True)
    pointer.write_text(FEATURE + "\n")
    status = _git(root, "status", "--porcelain=v1", "--untracked-files=all")
    assert status.splitlines() == snapshot["git_status"], (
        "ERROR fixture replay: the rebuilt working tree differs from the record"
    )
    return RecordedHost(
        root, root / "plans" / FEATURE / "state.yaml", snapshot["recorded"]
    )


_CLOSURE_KEYS = (
    "assignment_id",
    "role",
    "scope",
    "closed",
    "open_refs",
    "rounds_used",
    "calls_completed",
    "missing_slots",
    "next_step",
    "stop_reason",
    "decision_ids",
    "evidence_state",
)
_REVIEW_STATUS_KEYS = (
    "gate",
    "scope",
    "run_id",
    "execution",
    "disposition",
    "applicability",
    "evidence_state",
)
_VERIFICATION_KEYS = (
    "scope",
    "freshness",
    "evidence_state",
    "applicability",
    "accepted_degraded",
    "waived_rerun",
)


def status_projection(envelope: dict[str, Any]) -> dict[str, Any]:
    """The status and freshness results, without wording or additive fields.

    An assignment's current basis is kept once it holds a review call; an
    assignment with no call yet has no recorded result to compare.
    """
    data = envelope["data"]
    closure = []
    for row in data["review_closure"]["assignments"]:
        item = {key: row[key] for key in _CLOSURE_KEYS}
        item["evidence_basis"] = (
            row["evidence_basis"] if row["calls_completed"] else None
        )
        acceptance = row.get("acceptance")
        item["acceptance"] = (
            None
            if acceptance is None
            else {
                key: acceptance[key]
                for key in ("boundary", "scope", "source_identity", "revision")
            }
        )
        item["explanations"] = [
            {
                "subject": explanation["subject"],
                "failed_reference": explanation["failed_reference"],
                "changed_dependencies": explanation["changed_dependencies"],
            }
            for explanation in row["evidence_explanations"]
        ]
        closure.append(item)
    return {
        "stage": data["stage"],
        "blocking_conditions": data["blocking_conditions"],
        "gate_convergence_phase": data["gate_convergence_phase"],
        "review_closure": closure,
        "review_status": [
            {
                **{key: row[key] for key in _REVIEW_STATUS_KEYS},
                "evidence_basis": row["evidence_basis"] if row["run_id"] else None,
            }
            for row in data["review_status"]
        ],
        "verification_status": [
            {
                **{key: row.get(key) for key in _VERIFICATION_KEYS},
                "action": row["action"] is not None,
            }
            for row in data["verification_status"]
        ],
        "next_actions": [action["command"] for action in envelope["next_actions"]],
    }


def validation_codes(envelope: dict[str, Any]) -> list[str]:
    return sorted(diagnostic["code"] for diagnostic in envelope["diagnostics"])
